#ifndef ORM_LOG_H
#define ORM_LOG_H

/*
 * @brief Макросы журнала ORM.
 * @details
 * Вынесены в отдельный файл, потому что ими пользуются несколько заголовков
 * ORM (connection.h, database.h, table_macro.h). Если держать их в одном из
 * них, остальные получают макрос раньше его определения — в момент разбора
 * файла макроса ещё не существует, и сборка падает.
 *
 * Имена с префиксом ORM_, потому что у db_manager свои макросы журнала:
 * одинаковые имена давали бы переопределение, и чей макрос сработает,
 * зависело бы от порядка включения файлов.
 *
 * Макросы, а не функции: __FILE__ и __LINE__ должны подставиться в точке
 * вызова, иначе в журнале будет всегда одна и та же строка — эта.
 */

#include <QDebug>

#define ORM_ERROR_LOG(msg)                                                     \
    qWarning().nospace() << "[ORM_ERROR:" << __FILE__ << ":" << __LINE__       \
                         << "]: " << msg

#define ORM_DEBUG_LOG(msg)                                                     \
    qDebug().nospace() << "[ORM_INFO]: " << msg

#endif // ORM_LOG_H
